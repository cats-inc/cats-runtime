import { mkdtempSync, mkdirSync, readFileSync, rmSync, writeFileSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { dirname, join, resolve } from 'node:path';
import { spawnSync } from 'node:child_process';
import { createRequire } from 'node:module';
import { fileURLToPath } from 'node:url';

const require = createRequire(import.meta.url);
const scriptDir = dirname(fileURLToPath(import.meta.url));
const runtimeRoot = resolve(scriptDir, '..');
const inputPath = join(runtimeRoot, 'src', 'http', 'ui', 'tailwind.runtime.css');
const configPath = join(runtimeRoot, 'tailwind.runtime.config.cjs');
const generatedDir = join(runtimeRoot, 'src', 'http', 'ui', 'generated');
const generatedModulePath = join(generatedDir, 'runtimeTailwind.ts');
const tailwindCliPath = require.resolve('tailwindcss/lib/cli.js');

function main() {
  mkdirSync(generatedDir, { recursive: true });

  const tempDir = mkdtempSync(join(tmpdir(), 'cats-runtime-ui-'));
  const outputCssPath = join(tempDir, 'runtime-ui.css');
  try {
    const result = spawnSync(
      process.execPath,
      [
        tailwindCliPath,
        '-c',
        configPath,
        '-i',
        inputPath,
        '-o',
        outputCssPath,
        '--minify',
      ],
      {
        cwd: runtimeRoot,
        encoding: 'utf8',
        windowsHide: true,
      },
    );

    if (result.status !== 0) {
      throw new Error(
        result.stderr
          || result.stdout
          || result.error?.message
          || 'Tailwind UI build failed.',
      );
    }

    const css = readFileSync(outputCssPath, 'utf8');
    const moduleSource = `// Generated by scripts/build-runtime-ui-css.mjs. Do not edit manually.\n`
      + `export const GENERATED_RUNTIME_TAILWIND_CSS = ${JSON.stringify(css)} as const;\n`;
    writeFileSync(generatedModulePath, moduleSource);
  } finally {
    rmSync(tempDir, { recursive: true, force: true });
  }
}

main();
